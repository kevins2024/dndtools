#!/usr/bin/env node
// Builds engine/FEATURE_MECHANICS_CHECKLIST.md. Read-only over the data; no dependencies.
// Re-runnable: statuses/notes already in the file are preserved (merged by id, or by
// character+feature name for the "no id" section). A `todo` row becomes `done` once the
// id has a feature-mechanics.json entry.
const fs = require('fs')
const path = require('path')
const root = path.join(__dirname, '..')
const rd = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'))
const OUT = path.join(root, 'engine/FEATURE_MECHANICS_CHECKLIST.md')
const STATUSES = ['todo', 'done', 'text-only', 'needs-engine', 'needs-owner']

const published = rd('src/data/published_features.json')
const catalog = rd('engine/data/5e/feature-catalog.json')
const mech = rd('engine/data/5e/feature-mechanics.json')
const chars = rd('src/data/characters.json')
let srd = []
try { srd = rd('src/data/api_data_cache/features.json') } catch (e) {}

const rows = new Map() // id -> row
const row = (id) => {
  if (!rows.has(id)) rows.set(id, { id, name: '', source: '', homebrew: '', users: new Set() })
  return rows.get(id)
}
for (const f of published) {
  const r = row(f.id)
  r.name = f.name
  r.source = f.class || f.source || ''
  r.homebrew = f.homebrew ? 'yes' : 'no'
}
const srdById = new Map(srd.map((f) => [f.index, f]))
const refSource = new Map()
const dir = (d) => fs.readdirSync(path.join(root, d)).filter((f) => f.endsWith('.json')).map((f) => rd(d + '/' + f))
for (const c of dir('engine/data/5e/classes')) {
  for (const ids of Object.values(c.features_by_level || {})) for (const id of ids) if (!refSource.has(id)) refSource.set(id, c.name)
}
for (const s of dir('engine/data/5e/subclasses')) {
  for (const ids of Object.values(s.features_by_level || {})) for (const id of ids) if (!refSource.has(id)) refSource.set(id, `${s.class} (${s.name})`)
}
for (const id of refSource.keys()) row(id)
const noId = []
for (const ch of chars) {
  for (const ft of ch.features || []) {
    if (ft.id) row(ft.id).users.add(ch.name)
    else noId.push({ character: ch.name, name: ft.name })
  }
}
for (const r of rows.values()) {
  const s = srdById.get(r.id)
  if (!r.name) r.name = (s && s.name) || catalog[r.id] || ''
  if (!r.source) r.source = refSource.get(r.id) || (s && s.class && s.class.name) || ''
  if (!r.homebrew) r.homebrew = s || catalog[r.id] ? 'no' : '?'
  if (!r.source && s) r.source = 'SRD'
}

// ---- parse existing file
const prev = new Map()
const prevNoId = new Map()
const split = (line) => line.replace(/^\|\s*/, '').replace(/\s*\|\s*$/, '').split(/\s+\|\s+/).map((c) => c.replace(/\\\|/g, '|'))
if (fs.existsSync(OUT)) {
  let sec = ''
  for (const line of fs.readFileSync(OUT, 'utf8').split('\n')) {
    if (line.startsWith('## ')) sec = line
    if (!line.startsWith('| ') || line.startsWith('| id ') || line.startsWith('| character ')) continue
    const c = split(line)
    if (sec.includes('Features') && c.length >= 7) prev.set(c[0], { status: c[5], notes: c[6] })
    else if (sec.includes('no id') && c.length >= 4) prevNoId.set(c[0] + '::' + c[1], { status: c[2], notes: c[3] })
  }
}
const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
const list = [...rows.values()].map((r) => {
  const p = prev.get(r.id)
  let status = p && STATUSES.includes(p.status) ? p.status : 'todo'
  if (mech[r.id] && status === 'todo') status = 'done'
  return { ...r, status, notes: p ? p.notes : '' }
})
list.sort((a, b) => (b.users.size > 0) - (a.users.size > 0) || a.source.localeCompare(b.source) || a.name.localeCompare(b.name) || a.id.localeCompare(b.id))

const count = {}
for (const r of list) count[r.status] = (count[r.status] || 0) + 1
const out = []
out.push('# Feature mechanics checklist', '')
out.push('Generated by `node scripts/build-feature-checklist.js` (safe to re-run; statuses and notes are preserved by id).')
out.push('Statuses: `todo`, `done`, `text-only`, `needs-engine`, `needs-owner`. Edit status/notes in place; everything else is regenerated.', '')
out.push('Counts: ' + STATUSES.map((s) => `${s} ${count[s] || 0}`).join(' · ') + ` · total ${list.length}`, '')
out.push('## Features (roster-used first)', '')
out.push('| id | name | class/source | homebrew? | used by | status | notes |', '|---|---|---|---|---|---|---|')
for (const r of list) out.push(`| ${esc(r.id)} | ${esc(r.name)} | ${esc(r.source)} | ${r.homebrew} | ${esc([...r.users].join(', '))} | ${r.status} | ${esc(r.notes)} |`)
out.push('', '## Roster features with no id', '')
out.push('| character | feature | status | notes |', '|---|---|---|---|')
const seen = new Set()
for (const n of noId) {
  const k = n.character + '::' + n.name
  const p = prevNoId.get(k)
  out.push(`| ${esc(n.character)} | ${esc(n.name)} | ${p ? p.status : 'todo'} | ${esc(p ? p.notes : '')} |`)
  seen.add(k)
}
out.push('')
fs.writeFileSync(OUT, out.join('\n'))
console.log(`wrote ${path.relative(root, OUT)}: ${list.length} features, ${noId.length} without id; ` + JSON.stringify(count))
