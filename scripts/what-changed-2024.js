// Writes 2024_WHAT_CHANGED.md: for each class, what the 2024 rules changed relative to 2014,
// computed from the two data trees (so it can't drift from what the engine actually does).
//
//   node scripts/what-changed-2024.js            # print
//   node scripts/what-changed-2024.js --write

const fs = require('fs')
const path = require('path')
const { loadClass, listClasses } = require('../engine/rules/5e/classFeatures')
const { hitDieForClass } = require('../engine/rules/5e/progression')

const base = (n) =>
  n
    .replace(/\s*\(.*\)\s*$/, '')
    .trim()
    .toLowerCase()
const names = (c) => {
  const m = new Map()
  for (const [lvl, list] of Object.entries(c.features_by_level))
    for (const n of list) if (!m.has(base(n))) m.set(base(n), Number(lvl))
  return m
}
const pretty = (s) =>
  s.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())
const title = (n) =>
  n
    .replace(/(^|[\s-])([a-z])/g, (m) => m.toUpperCase())
    .replace(/\b(Of|On|And|The|In|For|To)\b/g, (m) => m.toLowerCase())
const list = (xs) => (xs.length ? xs.join(', ') : 'none')

const out = []
out.push(`# What changed from 2014 to 2024, by class

Generated by \`node scripts/what-changed-2024.js --write\` from the 2014 and 2024 data trees, so it
lists what the engine actually does. It covers class chassis (features, levels, skills, subclass
level). Subclass-by-subclass changes are in the data files themselves.

## Rules that changed for everyone (the ones that affect how you build and play)

These are implemented and tested in the engine. Each was checked against the SRD 5.2 text.

- **Ability scores come from your background, not your species.** Species give no ability bonus.
  A background gives +2/+1 or +1/+1/+1 among three listed scores.
- **Every background grants an Origin feat**, plus two skills and a tool proficiency.
- **Weapon Mastery.** Barbarian, Fighter, Paladin, Ranger and Rogue pick weapons whose mastery
  property (Cleave, Graze, Nick, Push, Sap, Slow, Topple, Vex) they can use.
- **Fighting Style is a feat** (the Fighting Style category). Warlock Pact Boon is gone; the Pacts
  are Eldritch Invocations.
- **Prepared spells are a fixed number per class level**, taken from the class table. There is no
  "level + ability modifier" formula any more.
- **Paladin and Ranger cast from level 1**, and count half their level, rounded up, toward
  multiclass spell slots.
- **A Long Rest restores all your Hit Point Dice** (2014: half of them). A Short Rest can return one
  use of some features.
- **Exhaustion** is -2 per level to every D20 Test and -5 feet of Speed per level.
- **Multiclass prerequisite** is 13 in the primary ability of your new class and of your current one.
- **Epic Boons** arrive at level 19 as the Ability Score Improvement feat.

## Class by class
`)

const rows = []
for (const c of listClasses('2024').map((x) =>
  typeof x === 'string' ? x : x.name
)) {
  const a = loadClass(c, '2014')
  const b = loadClass(c, '2024')
  if (!a || !b) continue
  const fa = names(a)
  const fb = names(b)
  // 2014 casters keep Spellcasting out of features_by_level; it isn't new.
  const added = [...fb].filter(
    ([n]) => !fa.has(n) && !(n === 'spellcasting' && a.spellcasting)
  )
  const removed = [...fa].filter(([n]) => !fb.has(n))
  const moved = [...fb].filter(([n, l]) => fa.has(n) && fa.get(n) !== l)
  const skills = (x) =>
    Array.isArray(x.skill_choices?.options)
      ? x.skill_choices.options.map(pretty)
      : []
  const gainedSk = skills(b).filter((s) => !skills(a).includes(s))
  const lostSk = skills(a).filter((s) => !skills(b).includes(s))
  out.push(`### ${c}
- Hit die d${hitDieForClass(c)}. Subclass at level ${
    b.subclass_choice_level
  } (2014: ${a.subclass_choice_level}).
- Class skills: choose ${b.skill_choices?.count} (2014: ${
    a.skill_choices?.count
  })${gainedSk.length ? `; added ${list(gainedSk)}` : ''}${
    lostSk.length ? `; removed ${list(lostSk)}` : ''
  }.
- New in 2024: ${list(added.map(([n, l]) => `${title(n)} (L${l})`))}.
- Gone in 2024: ${list(removed.map(([n, l]) => `${title(n)} (L${l})`))}.
- Same feature, different level: ${list(
    moved.map(([n, l]) => `${title(n)} L${fa.get(n)}→L${l}`)
  )}.
`)
  rows.push(c)
}
out.push(`Classes covered: ${rows.join(', ')}.\n`)
const text = out.join('\n')
if (process.argv.includes('--write'))
  fs.writeFileSync(path.join(__dirname, '..', '2024_WHAT_CHANGED.md'), text)
else console.log(text)
